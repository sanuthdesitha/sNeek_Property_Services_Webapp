const sentDescriptions = () => m.pushInvoice.mock.calls[0][0].lineItems.map((item: { description: string }) => item.description);

describe("every entry point sends the grouped order", () => {
  it("the per-invoice route (v2 row menu, editor, v1 screen)", async () => {
    const response = await pushRoute(new NextRequest("http://localhost/api/admin/invoices/inv/xero-push", { method: "POST" }), { params: { id: "inv" } });
    expect(response.status).toBe(200);
    expect(sentDescriptions()).toEqual(GROUPED_DESCRIPTIONS);
  });

  it("the bulk route's xero-push", async () => {
    const response = await runClientInvoiceBulk({ request: { action: "xero-push", ids: ["inv"] }, actor: { id: "admin", role: "ADMIN" }, origin: "https://app.test" });
    expect(response.results[0]).toMatchObject({ ok: true, outcome: "done" });
    expect(sentDescriptions()).toEqual(GROUPED_DESCRIPTIONS);
  });

  it("Push to Xero when sent", async () => {
    const result = await sendClientInvoice({ invoiceId: "inv", origin: "https://app.test", actorId: "admin", options: { pushToXero: true } });
    expect(result.status).toBe(200);
    expect((result.body as { xeroPush?: { outcome: string } }).xeroPush?.outcome).toBe("pushed");
    expect(sentDescriptions()).toEqual(GROUPED_DESCRIPTIONS);
  });

  it("a credit note: grouped order, positive Xero amounts, same total", async () => {
    const lines = mixedLines().map((line) => ({ ...line, unitPrice: -line.unitPrice, lineTotal: -line.lineTotal }));
    Object.assign(stored, { kind: "CREDIT_NOTE", status: "APPROVED", invoiceNumber: "CN-1", creditsInvoice: { invoiceNumber: "INV-1" }, lines });
    const response = await pushRoute(new NextRequest("http://localhost/api/admin/invoices/inv/xero-push", { method: "POST" }), { params: { id: "inv" } });
    expect(response.status).toBe(200);
    const items = m.pushCredit.mock.calls[0][0].lineItems as Array<{ description: string; quantity: number; unitAmount: number }>;
    expect(items.map((item) => item.description)).toEqual(GROUPED_DESCRIPTIONS);
    expect(items.every((item) => item.unitAmount > 0)).toBe(true);
    expect(total(items)).toBe(total(storedOrderItems(mixedLines())));
  });

  it("never writes a line's stored sortOrder while pushing", async () => {
    await pushRoute(new NextRequest("http://localhost/api/admin/invoices/inv/xero-push", { method: "POST" }), { params: { id: "inv" } });
    const writes = m.update.mock.calls.map(([args]) => args.data);
    expect(writes.some((data: Record<string, unknown>) => "sortOrder" in data || "lines" in data)).toBe(false);
  });
});

describe("no path to Xero bypasses the one push function", () => {
  const ROOT = join(__dirname, "../..");
  const SKIP = new Set(["node_modules", ".next", "mobile", "mobile-app", "sneek-nextgen", "tests", ".git"]);
  function sources(dir: string, found: string[] = []): string[] {
    for (const name of readdirSync(dir)) {
      if (SKIP.has(name) || name.startsWith(".next")) continue;
      const path = join(dir, name);
      if (statSync(path).isDirectory()) sources(path, found);
      else if (/\.(ts|tsx)$/.test(name)) found.push(relative(ROOT, path));
    }
    return found;
  }
  const files = ["app", "lib", "components", "workers", "scripts"].flatMap((dir) => sources(join(ROOT, dir)));

  it("only the push and the update call the Xero client's client-invoice writers", () => {
    const callers = files.filter((file) => /pushClientInvoiceToXero\(|pushClientCreditNoteToXero\(|updateClientDocumentInXero\(/.test(readFileSync(join(ROOT, file), "utf8")));
    expect(callers.sort()).toEqual(["lib/billing/client-invoice-xero-update.ts", "lib/billing/client-invoice-xero.ts", "lib/xero/client.ts"]);
  });

  it("the v1 screen and the v2 list call the shared per-invoice push route", () => {
    expect(readFileSync(join(ROOT, "components/admin/client-invoices-page.tsx"), "utf8")).toContain("/api/admin/invoices/${selected.id}/xero-push");
    expect(readFileSync(join(ROOT, "components/v2/admin/finance/invoices/invoice-requests.ts"), "utf8")).toContain("/api/admin/invoices/${id}/xero-push");
  });
});
