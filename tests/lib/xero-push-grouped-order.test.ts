const settings = { defaultAccountCode: "200", disbursementAccountCode: "800", salesTaxType: "OUTPUT2", defaultItemCode: "CLEAN", itemCodeByService: { DEEP_CLEAN: "DEEP" } };

/** What the push sent BEFORE this change: stored order, same mapping. */
function storedOrderItems(lines: Line[]) {
  return lines.map((line) => ({
    description: `${line.description}${line.job?.jobNumber ? ` · Job ${line.job.jobNumber}` : ""}${line.note ? ` — ${line.note}` : ""}`,
    quantity: line.quantity,
    unitAmount: line.unitPrice,
    accountCode: "200",
    taxType: "OUTPUT2",
    itemCode: line.job?.jobType === "DEEP_CLEAN" ? "DEEP" : "CLEAN",
  }));
}

const amountKey = (item: { quantity: number; unitAmount: number; accountCode?: string; taxType?: string; itemCode?: string }) =>
  JSON.stringify([item.quantity, item.unitAmount, item.accountCode, item.taxType, item.itemCode]);
const total = (items: Array<{ quantity: number; unitAmount: number }>) =>
  Number(items.reduce((sum, item) => sum + item.quantity * item.unitAmount, 0).toFixed(2));

const GROUPED_DESCRIPTIONS = [
  "Bondi Flat - TURNOVER - 02 Oct 2026 · Job J2 — Late checkout",
  "Bondi Flat - DEEP CLEAN - 03 Oct 2026 · Job J3",
  "Manly House - TURNOVER - 01 Oct 2026 · Job J1",
  "Manly House - Linen top-up",
  "Call-out fee",
  "Repair to door",
];

describe("the PDF's order for Xero (pure)", () => {
  it("groups by property like the PDF and prefixes a manual line whose description lacks its property", () => {
    const items = buildXeroLineItems(mixedLines(), settings, "OUTPUT2");
    expect(items.map((item) => item.description)).toEqual(GROUPED_DESCRIPTIONS);
  });

  it("changes only the order: the same amounts, codes and total as before", () => {
    const lines = mixedLines();
    const before = storedOrderItems(lines);
    const after = buildXeroLineItems(lines, settings, "OUTPUT2");
    expect(after.map(amountKey).sort()).toEqual(before.map(amountKey).sort());
    expect(total(after)).toBe(total(before));
    expect(after.map(amountKey)).not.toEqual(before.map(amountKey));
  });

  it("leaves a single-property invoice exactly in its stored order with its descriptions", () => {
    const lines = mixedLines().filter((line) => line.job?.property === bondi || line.property === bondi).filter((line) => line.category === "SERVICE");
    lines.push({ ...lines[0], id: "l7", description: "Extra towels", job: null, property: bondi });
    const order = xeroLineOrder(lines);
    expect(order.grouped).toBe(false);
    const items = buildXeroLineItems(lines, settings, "OUTPUT2");
    expect(items).toEqual(storedOrderItems(lines));
  });

  it("never alters the stored lines it orders", () => {
    const lines = mixedLines();
    const snapshot = JSON.stringify(lines);
    buildXeroLineItems(lines, settings, "OUTPUT2");
    expect(JSON.stringify(lines)).toBe(snapshot);
  });
});

