import { test, expect } from "@playwright/test";
import { build } from "esbuild";
import path from "node:path";
import fs from "node:fs/promises";
import postcss from "postcss";
import tailwind from "tailwindcss";
let bundle: string, css: string;
test.beforeAll(async () => { bundle = (await build({ entryPoints: [path.resolve("e2e/admin/fixtures/social-composer-entry.tsx")], bundle: true, write: false, format: "iife", platform: "browser", jsx: "automatic", define: { "process.env": "{}", "process.env.NODE_ENV": '"test"' }, alias: { "@": process.cwd() }, logLevel: "silent" })).outputFiles[0].text; css = (await postcss([tailwind({ config: path.resolve("tailwind.config.ts") })]).process(await fs.readFile("app/globals.css", "utf8"), { from: "app/globals.css" })).css + await fs.readFile("app/v2/estate.css", "utf8"); });
test("v2 social draft generates a preview before explicitly applying it", async ({ page }) => {
  let generated = 0; let saved = 0;
  await page.route("**/__social_composer", route => route.fulfill({ contentType: "text/html", body: '<html><head><meta name="viewport" content="width=device-width, initial-scale=1" /></head><body><div id="root"></div></body></html>' }));
  await page.route("**/api/admin/marketing/ai-compose", route => { generated++; expect(route.request().postDataJSON().platform).toBe("FACEBOOK"); return route.fulfill({ json: { caption: "A fresh welcome for your guests.", hashtags: ["#Sydney"], suggestedHook: "Welcome" } }); });
  await page.route("**/api/admin/marketing/social", route => { saved++; return route.fulfill({ status: 500, json: { error: "Unexpected save" } }); });
  await page.goto("/__social_composer"); await page.addScriptTag({ content: bundle }); await page.addStyleTag({ content: css });
  await page.getByRole("button", { name: "New draft" }).click();
  await expect(page.getByRole("button", { name: "Generate with AI" })).toBeDisabled();
  await page.getByLabel("Channel", { exact: true }).selectOption("FACEBOOK");
  await page.getByLabel("Topic", { exact: true }).fill("Airbnb turnover cleaning in Sydney");
  await page.getByLabel("Caption", { exact: true }).fill("My original draft");
  await page.getByRole("button", { name: "Generate with AI" }).click();
  await expect(page.getByText("Generated suggestion")).toBeVisible();
  await expect(page.getByLabel("Caption", { exact: true })).toHaveValue("My original draft");
  expect(generated).toBe(1); expect(saved).toBe(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
  await page.getByRole("button", { name: "Use generated caption" }).click();
  await expect(page.getByLabel("Caption", { exact: true })).toHaveValue("A fresh welcome for your guests.\n\n#Sydney");
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0); expect(saved).toBe(0);
});
